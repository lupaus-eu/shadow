#!/usr/bin/env bash
set -euo pipefail

readonly REPOSITORY_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly OUTPUT_FILE="${1:-${REPOSITORY_ROOT}/.env.authentik.local}"

if [[ -e "${OUTPUT_FILE}" ]]; then
  printf 'Refusing to overwrite existing local secrets: %s\n' "${OUTPUT_FILE}" >&2
  printf 'Remove it only when you also intend to reset the local Authentik volumes.\n' >&2
  exit 1
fi

command -v python3 >/dev/null || {
  printf 'python3 is required\n' >&2
  exit 1
}
command -v openssl >/dev/null || {
  printf 'openssl is required\n' >&2
  exit 1
}

random_password() {
  openssl rand -base64 24 | tr -d '\n'
}

random_hex() {
  openssl rand -hex "$1"
}

hash_password() {
  printf '%s' "$1" | python3 -c '
import base64
import hashlib
import secrets
import string
import sys

password = sys.stdin.buffer.read()
salt = "".join(secrets.choice(string.ascii_letters + string.digits) for _ in range(22))
iterations = 1_000_000
digest = hashlib.pbkdf2_hmac("sha256", password, salt.encode(), iterations)
encoded = base64.b64encode(digest).decode("ascii")
print(f"pbkdf2_sha256${iterations}${salt}${encoded}")
'
}

authentik_secret_key="$(random_hex 60)"
bootstrap_password="$(random_password)"
consultant_password="$(random_password)"
admin_password="$(random_password)"
unmatched_password="$(random_password)"

printf 'Generating Authentik-compatible salted password hashes...\n'
bootstrap_hash="$(hash_password "${bootstrap_password}")"
consultant_hash="$(hash_password "${consultant_password}")"
admin_hash="$(hash_password "${admin_password}")"
unmatched_hash="$(hash_password "${unmatched_password}")"

umask 077
temporary_file="$(mktemp "${OUTPUT_FILE}.tmp.XXXXXX")"
trap 'rm -f "${temporary_file}"' EXIT

{
  printf '# Generated by scripts/setup-local-authentik.sh. Do not commit.\n'
  printf 'AUTHENTIK_POSTGRESQL_PASSWORD=%s\n' "$(random_hex 32)"
  printf 'AUTHENTIK_SECRET_KEY=%s\n' "${authentik_secret_key}"
  printf 'SCHATTEN_OIDC_CLIENT_SECRET=%s\n' "$(random_hex 48)"
  printf "AUTHENTIK_BOOTSTRAP_PASSWORD_HASH='%s'\n" "${bootstrap_hash}"
  printf "AUTHENTIK_CONSULTANT_PASSWORD_HASH='%s'\n" "${consultant_hash}"
  printf "AUTHENTIK_ADMIN_PASSWORD_HASH='%s'\n" "${admin_hash}"
  printf "AUTHENTIK_UNMATCHED_PASSWORD_HASH='%s'\n" "${unmatched_hash}"
} >"${temporary_file}"

mv "${temporary_file}" "${OUTPUT_FILE}"
trap - EXIT

printf '\nCreated %s with mode 600. Passwords are shown once; store them in your password manager if needed.\n' "${OUTPUT_FILE}"
printf '  Authentik administrator (akadmin): %s\n' "${bootstrap_password}"
printf '  Schatten consultant (schatten-consultant): %s\n' "${consultant_password}"
printf '  Schatten admin (schatten-admin): %s\n' "${admin_password}"
printf '  Unmatched negative-test user (schatten-unmatched): %s\n' "${unmatched_password}"
printf '\nOnly salted hashes were written to disk; no bootstrap API token was created.\n'

"${REPOSITORY_ROOT}/scripts/setup-local-authentik-tls.sh"
