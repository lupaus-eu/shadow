#!/usr/bin/env bash
set -euo pipefail

readonly REPOSITORY_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly OUTPUT_FILE="${1:-${REPOSITORY_ROOT}/.env.entra.local}"

if [[ -e "${OUTPUT_FILE}" ]]; then
  printf 'Refusing to overwrite existing local Entra configuration: %s\n' "${OUTPUT_FILE}" >&2
  exit 1
fi

read -r -p 'Application (client) ID: ' application_client_id
read -r -p 'Directory (tenant) ID: ' directory_tenant_id
read -r -s -p 'Client secret value: ' client_secret
printf '\n'

uuid_pattern='^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
if [[ ! "${application_client_id}" =~ ${uuid_pattern} ]]; then
  printf 'Application client ID must be a UUID.\n' >&2
  exit 1
fi
if [[ ! "${directory_tenant_id}" =~ ${uuid_pattern} ]]; then
  printf 'Directory tenant ID must be a UUID.\n' >&2
  exit 1
fi
if [[ -z "${client_secret}" || "${client_secret}" =~ [[:space:]] || ! "${client_secret}" =~ ^[A-Za-z0-9._~-]+$ ]]; then
  printf 'Client secret must be non-empty and contain only expected Entra secret characters.\n' >&2
  exit 1
fi

umask 077
temporary_file="$(mktemp "${OUTPUT_FILE}.tmp.XXXXXX")"
trap 'rm -f "${temporary_file}"' EXIT

{
  printf '# Generated by scripts/setup-local-entra.sh. Do not commit.\n'
  printf 'OIDC_DISCOVERY_URL=https://login.microsoftonline.com/%s/v2.0/.well-known/openid-configuration\n' "${directory_tenant_id}"
  printf 'OIDC_ISSUER=https://login.microsoftonline.com/%s/v2.0\n' "${directory_tenant_id}"
  printf 'OIDC_CLIENT_ID=%s\n' "${application_client_id}"
  printf 'OIDC_CLIENT_SECRET=%s\n' "${client_secret}"
} >"${temporary_file}"

mv "${temporary_file}" "${OUTPUT_FILE}"
trap - EXIT

printf 'Created %s with mode 600. No value was printed.\n' "${OUTPUT_FILE}"
printf 'Run the local-only administrator provisioning command separately; it prompts for identity input and never accepts it as command arguments.\n'
