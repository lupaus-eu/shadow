ALTER TABLE timeserie_values
    ADD COLUMN is_derived BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE derived_metrics_equations (
    derived_metric_equation_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    scenario_id BIGINT NOT NULL REFERENCES scenarios(scenario_id) ON DELETE CASCADE,
    derived_timeserie_id BIGINT NOT NULL REFERENCES timeseries(timeserie_id) ON DELETE CASCADE,
    formula TEXT NOT NULL,
    referenced_timeserie_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ,
    CONSTRAINT ck_derived_metrics_equations_formula_non_blank CHECK (formula ~ '[^[:space:]]')
);

CREATE UNIQUE INDEX ux_derived_metrics_equations_derived_timeserie_active
    ON derived_metrics_equations (derived_timeserie_id)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_derived_metrics_equations_scenario_active
    ON derived_metrics_equations (scenario_id)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_derived_metrics_equations_references_active
    ON derived_metrics_equations USING GIN (referenced_timeserie_ids)
    WHERE deleted_time IS NULL;
