-- Migration 004 discarded the original graph-to-org-state association and graph
-- metadata. Recreate a deterministic graph only when the remaining scenario link
-- maps every affected scenario to exactly one organisation state.

DO $$
BEGIN
    IF EXISTS (
        SELECT affected.scenario_id
        FROM (
            SELECT scenario_id FROM graph_nodes
            UNION
            SELECT scenario_id FROM graph_edges
        ) affected
        LEFT JOIN org_states os ON os.scenario_id = affected.scenario_id
        GROUP BY affected.scenario_id
        HAVING count(os.org_state_id) <> 1
    ) THEN
        RAISE EXCEPTION
            'Cannot revert migration 004: graph data does not map to exactly one org_state per scenario';
    END IF;
END $$;

CREATE TABLE graphs (
    graph_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    org_state_id BIGINT NOT NULL REFERENCES org_states(org_state_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ
);

INSERT INTO graphs (
    org_state_id,
    name,
    description,
    created_by,
    created_time,
    modified_by,
    modified_time,
    deleted_by,
    deleted_time
)
SELECT
    org_state_id,
    name,
    description,
    created_by,
    created_time,
    modified_by,
    modified_time,
    deleted_by,
    deleted_time
FROM org_states;

ALTER TABLE graph_nodes
    ADD COLUMN graph_id BIGINT;

ALTER TABLE graph_edges
    ADD COLUMN graph_id BIGINT;

UPDATE graph_nodes gn
SET graph_id = g.graph_id
FROM graphs g
JOIN org_states os ON os.org_state_id = g.org_state_id
WHERE os.scenario_id = gn.scenario_id;

UPDATE graph_edges ge
SET graph_id = g.graph_id
FROM graphs g
JOIN org_states os ON os.org_state_id = g.org_state_id
WHERE os.scenario_id = ge.scenario_id;

ALTER TABLE graph_nodes
    ALTER COLUMN graph_id SET NOT NULL,
    ADD CONSTRAINT graph_nodes_graph_id_fkey
        FOREIGN KEY (graph_id) REFERENCES graphs(graph_id) ON DELETE CASCADE;

ALTER TABLE graph_edges
    ALTER COLUMN graph_id SET NOT NULL,
    ADD CONSTRAINT graph_edges_graph_id_fkey
        FOREIGN KEY (graph_id) REFERENCES graphs(graph_id) ON DELETE CASCADE;

DROP INDEX idx_graph_nodes_scenario_active;
DROP INDEX idx_graph_nodes_scenario_type_active;
DROP INDEX idx_graph_nodes_scenario_create_date_active;
DROP INDEX ux_graph_nodes_scenario_key_active;
DROP INDEX idx_graph_edges_scenario_active;
DROP INDEX idx_graph_edges_scenario_type_active;
DROP INDEX idx_graph_edges_scenario_create_date_active;
DROP INDEX ux_graph_edges_scenario_key_active;

ALTER TABLE graph_nodes
    DROP CONSTRAINT fk_graph_nodes_scenario,
    DROP COLUMN scenario_id,
    DROP COLUMN name,
    DROP COLUMN description,
    ALTER COLUMN create_date DROP NOT NULL;

ALTER TABLE graph_edges
    DROP CONSTRAINT fk_graph_edges_scenario,
    DROP COLUMN scenario_id,
    DROP COLUMN name,
    DROP COLUMN description,
    ALTER COLUMN create_date DROP NOT NULL;

CREATE UNIQUE INDEX ux_graphs_org_state_active
    ON graphs (org_state_id)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_graph_nodes_graph_active
    ON graph_nodes (graph_id)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_graph_nodes_graph_type_active
    ON graph_nodes (graph_id, node_type_id)
    WHERE deleted_time IS NULL;

CREATE UNIQUE INDEX ux_graph_nodes_graph_key_active
    ON graph_nodes (graph_id, node_key)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_graph_edges_graph_active
    ON graph_edges (graph_id)
    WHERE deleted_time IS NULL;

CREATE INDEX idx_graph_edges_graph_type_active
    ON graph_edges (graph_id, edge_type_id)
    WHERE deleted_time IS NULL;

CREATE UNIQUE INDEX ux_graph_edges_graph_key_active
    ON graph_edges (graph_id, edge_key)
    WHERE deleted_time IS NULL;
