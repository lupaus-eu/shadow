CREATE TABLE customer_addresses (
    customer_address_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    address_line_1 TEXT NOT NULL,
    address_line_2 TEXT,
    postal_code TEXT,
    city TEXT,
    region TEXT,
    country_code TEXT NOT NULL,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ,
    CONSTRAINT ck_customer_addresses_label_non_blank
        CHECK (label ~ '[^[:space:]]'),
    CONSTRAINT ck_customer_addresses_address_line_1_non_blank
        CHECK (address_line_1 ~ '[^[:space:]]'),
    CONSTRAINT ck_customer_addresses_country_code
        CHECK (country_code COLLATE "C" ~ '^[A-Z]{2}$')
);

CREATE INDEX idx_customer_addresses_customer_label_active
    ON customer_addresses (customer_id, lower(label), customer_address_id)
    WHERE deleted_time IS NULL;
