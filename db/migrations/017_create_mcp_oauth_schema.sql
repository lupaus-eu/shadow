-- ADR-015: Schatten as the OAuth 2.1 authorization server for MCP clients.
-- Request ids, codes and tokens are stored only as SHA-256 hashes.

CREATE TABLE mcp_oauth_clients (
    mcp_oauth_client_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    redirect_uris JSONB NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_ip TEXT,
    last_used_time TIMESTAMPTZ,
    deleted_time TIMESTAMPTZ,
    CONSTRAINT uq_mcp_oauth_clients_client_id UNIQUE (client_id),
    CONSTRAINT ck_mcp_oauth_clients_client_id_non_blank
        CHECK (client_id ~ '[^[:space:]]'),
    CONSTRAINT ck_mcp_oauth_clients_client_name_length
        CHECK (length(client_name) BETWEEN 1 AND 100),
    CONSTRAINT ck_mcp_oauth_clients_redirect_uris
        CHECK (
            jsonb_typeof(redirect_uris) = 'array'
            AND jsonb_array_length(redirect_uris) BETWEEN 1 AND 10
        ),
    CONSTRAINT ck_mcp_oauth_clients_created_ip_non_blank
        CHECK (created_ip IS NULL OR created_ip ~ '[^[:space:]]')
);

CREATE INDEX idx_mcp_oauth_clients_stale
    ON mcp_oauth_clients ((COALESCE(last_used_time, created_time)))
    WHERE deleted_time IS NULL;

CREATE INDEX idx_mcp_oauth_clients_deleted_time
    ON mcp_oauth_clients (deleted_time)
    WHERE deleted_time IS NOT NULL;

CREATE TABLE mcp_oauth_grants (
    grant_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    grant_key TEXT NOT NULL,
    mcp_oauth_client_id BIGINT NOT NULL
        REFERENCES mcp_oauth_clients(mcp_oauth_client_id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    scopes TEXT NOT NULL,
    resource TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_time TIMESTAMPTZ NOT NULL,
    last_used_time TIMESTAMPTZ,
    revoked_time TIMESTAMPTZ,
    revoked_by BIGINT REFERENCES users(user_id),
    CONSTRAINT uq_mcp_oauth_grants_key UNIQUE (grant_key),
    CONSTRAINT ck_mcp_oauth_grants_key_non_blank
        CHECK (grant_key ~ '[^[:space:]]'),
    CONSTRAINT ck_mcp_oauth_grants_scope
        CHECK (scopes IN ('schatten.read', 'schatten.write')),
    CONSTRAINT ck_mcp_oauth_grants_scope_resource
        CHECK (
            (scopes = 'schatten.read' AND resource LIKE '%/api/mcp/read')
            OR (scopes = 'schatten.write' AND resource LIKE '%/api/mcp/write')
        ),
    CONSTRAINT ck_mcp_oauth_grants_expiry
        CHECK (expires_time > created_time),
    CONSTRAINT ck_mcp_oauth_grants_revocation_audit
        CHECK (revoked_by IS NULL OR revoked_time IS NOT NULL)
);

CREATE INDEX idx_mcp_oauth_grants_user_id
    ON mcp_oauth_grants (user_id);

CREATE INDEX idx_mcp_oauth_grants_client_user_resource
    ON mcp_oauth_grants (mcp_oauth_client_id, user_id, resource);

CREATE INDEX idx_mcp_oauth_grants_expires_time
    ON mcp_oauth_grants (expires_time);

CREATE INDEX idx_mcp_oauth_grants_revoked_time
    ON mcp_oauth_grants (revoked_time)
    WHERE revoked_time IS NOT NULL;

CREATE TABLE mcp_oauth_authorization_requests (
    request_id_hash BYTEA PRIMARY KEY,
    mcp_oauth_client_id BIGINT NOT NULL
        REFERENCES mcp_oauth_clients(mcp_oauth_client_id) ON DELETE RESTRICT,
    redirect_uri TEXT NOT NULL,
    state TEXT,
    code_challenge TEXT NOT NULL,
    scopes TEXT NOT NULL,
    resource TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_time TIMESTAMPTZ NOT NULL,
    user_id BIGINT REFERENCES users(user_id),
    code_hash BYTEA,
    code_expires_time TIMESTAMPTZ,
    consumed_time TIMESTAMPTZ,
    grant_id BIGINT REFERENCES mcp_oauth_grants(grant_id) ON DELETE SET NULL,
    CONSTRAINT uq_mcp_oauth_authorization_requests_code_hash UNIQUE (code_hash),
    CONSTRAINT ck_mcp_oauth_authorization_requests_id_hash_length
        CHECK (octet_length(request_id_hash) = 32),
    CONSTRAINT ck_mcp_oauth_authorization_requests_code_hash_length
        CHECK (code_hash IS NULL OR octet_length(code_hash) = 32),
    CONSTRAINT ck_mcp_oauth_authorization_requests_redirect_uri
        CHECK (length(redirect_uri) BETWEEN 1 AND 2048),
    CONSTRAINT ck_mcp_oauth_authorization_requests_code_challenge
        CHECK (code_challenge ~ '^[A-Za-z0-9_-]{43}$'),
    CONSTRAINT ck_mcp_oauth_authorization_requests_scope
        CHECK (scopes IN ('schatten.read', 'schatten.write')),
    CONSTRAINT ck_mcp_oauth_authorization_requests_scope_resource
        CHECK (
            (scopes = 'schatten.read' AND resource LIKE '%/api/mcp/read')
            OR (scopes = 'schatten.write' AND resource LIKE '%/api/mcp/write')
        ),
    CONSTRAINT ck_mcp_oauth_authorization_requests_expiry
        CHECK (expires_time > created_time),
    CONSTRAINT ck_mcp_oauth_authorization_requests_code
        CHECK (
            (code_hash IS NULL) = (code_expires_time IS NULL)
            AND (code_hash IS NULL OR user_id IS NOT NULL)
        ),
    CONSTRAINT ck_mcp_oauth_authorization_requests_consumed
        CHECK (consumed_time IS NULL OR code_hash IS NOT NULL),
    CONSTRAINT ck_mcp_oauth_authorization_requests_grant
        CHECK (grant_id IS NULL OR consumed_time IS NOT NULL)
);

CREATE INDEX idx_mcp_oauth_authorization_requests_client
    ON mcp_oauth_authorization_requests (mcp_oauth_client_id);

CREATE INDEX idx_mcp_oauth_authorization_requests_expires_time
    ON mcp_oauth_authorization_requests (expires_time);

CREATE INDEX idx_mcp_oauth_authorization_requests_grant_id
    ON mcp_oauth_authorization_requests (grant_id)
    WHERE grant_id IS NOT NULL;

CREATE TABLE mcp_oauth_tokens (
    token_hash BYTEA PRIMARY KEY,
    grant_id BIGINT NOT NULL
        REFERENCES mcp_oauth_grants(grant_id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_time TIMESTAMPTZ NOT NULL,
    replaced_by_hash BYTEA,
    revoked_time TIMESTAMPTZ,
    CONSTRAINT ck_mcp_oauth_tokens_hash_length
        CHECK (octet_length(token_hash) = 32),
    CONSTRAINT ck_mcp_oauth_tokens_replaced_by_hash_length
        CHECK (replaced_by_hash IS NULL OR octet_length(replaced_by_hash) = 32),
    CONSTRAINT ck_mcp_oauth_tokens_kind
        CHECK (kind IN ('access', 'refresh')),
    CONSTRAINT ck_mcp_oauth_tokens_replacement_kind
        CHECK (replaced_by_hash IS NULL OR kind = 'refresh'),
    CONSTRAINT ck_mcp_oauth_tokens_expiry
        CHECK (expires_time > created_time)
);

CREATE INDEX idx_mcp_oauth_tokens_grant_id
    ON mcp_oauth_tokens (grant_id);

CREATE INDEX idx_mcp_oauth_tokens_access_expires_time
    ON mcp_oauth_tokens (expires_time)
    WHERE kind = 'access';

COMMENT ON TABLE mcp_oauth_tokens IS
    'Hashed MCP tokens. Replaced refresh tokens are kept until their grant expires or is revoked, for reuse detection.';
