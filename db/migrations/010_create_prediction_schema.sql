CREATE TABLE prediction_versions (
    prediction_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    organisation_id BIGINT NOT NULL REFERENCES organisations(organisation_id),
    prediction_key TEXT NOT NULL,
    name TEXT NOT NULL,
    cutoff_mode TEXT NOT NULL CHECK (cutoff_mode IN ('asOfStart', 'allCurrentReality')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    model_configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_prediction_versions_name_non_blank CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_prediction_versions_date_range CHECK (start_date < end_date)
);

CREATE UNIQUE INDEX ux_prediction_versions_key
    ON prediction_versions (prediction_key);
CREATE UNIQUE INDEX ux_prediction_versions_organisation_name
    ON prediction_versions (organisation_id, lower(name));

CREATE TABLE prediction_targets (
    prediction_target_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    prediction_version_id BIGINT NOT NULL REFERENCES prediction_versions(prediction_version_id) ON DELETE CASCADE,
    target_scenario_id BIGINT NOT NULL,
    target_scenario_key TEXT NOT NULL,
    reality_scenario_key TEXT NOT NULL,
    metric_key TEXT NOT NULL,
    metric_name TEXT NOT NULL,
    time_unit TEXT NOT NULL CHECK (time_unit IN ('day', 'week', 'month', 'year')),
    unit TEXT,
    eligibility_status TEXT NOT NULL CHECK (eligibility_status IN ('eligible', 'ineligible', 'requires_manual_seasonal_period')),
    eligibility_reason TEXT,
    seasonal_period INT,
    seasonal_period_source TEXT CHECK (seasonal_period_source IN ('automatic', 'manual')),
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    input_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_prediction_targets_metric_non_blank CHECK (metric_key ~ '[^[:space:]]'),
    CONSTRAINT ck_prediction_targets_seasonal_period CHECK (seasonal_period IS NULL OR seasonal_period >= 2)
);

CREATE INDEX idx_prediction_targets_version
    ON prediction_targets (prediction_version_id);

CREATE TABLE prediction_model_results (
    prediction_model_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    prediction_target_id BIGINT NOT NULL REFERENCES prediction_targets(prediction_target_id) ON DELETE CASCADE,
    result_kind TEXT NOT NULL CHECK (result_kind IN ('naive', 'seasonal_naive', 'average', 'mlforecast', 'sarima')),
    status TEXT NOT NULL CHECK (status IN ('available', 'ineligible')),
    reason TEXT,
    cross_validation_status TEXT NOT NULL CHECK (cross_validation_status IN ('available', 'unavailable', 'not_applicable')),
    cross_validation_mae DOUBLE PRECISION,
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_prediction_model_results_target_kind UNIQUE (prediction_target_id, result_kind),
    CONSTRAINT ck_prediction_model_results_cv_score CHECK (
        cross_validation_mae IS NULL OR (
            cross_validation_mae >= 0
            AND cross_validation_mae <> 'NaN'::float8
            AND cross_validation_mae <> 'Infinity'::float8
            AND cross_validation_mae <> '-Infinity'::float8
        )
    )
);

CREATE TABLE prediction_points (
    prediction_point_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    prediction_model_result_id BIGINT NOT NULL REFERENCES prediction_model_results(prediction_model_result_id) ON DELETE CASCADE,
    date DATE NOT NULL,
    value DOUBLE PRECISION NOT NULL,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_prediction_points_result_date UNIQUE (prediction_model_result_id, date),
    CONSTRAINT ck_prediction_points_value_finite CHECK (
        value <> 'NaN'::float8
        AND value <> 'Infinity'::float8
        AND value <> '-Infinity'::float8
    )
);

CREATE INDEX idx_prediction_points_result_date
    ON prediction_points (prediction_model_result_id, date);
