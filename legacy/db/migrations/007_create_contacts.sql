CREATE TABLE contacts (
    contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    job_title TEXT,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ,
    CONSTRAINT ck_contacts_name_non_blank
        CHECK (name ~ '[^[:space:]]')
);

CREATE INDEX idx_contacts_customer_name_active
    ON contacts (customer_id, lower(name), contact_id)
    WHERE deleted_time IS NULL;
