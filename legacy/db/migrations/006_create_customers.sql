CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ,
    CONSTRAINT ck_customers_name_non_blank
        CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_customers_status
        CHECK (status IN ('active', 'archived', 'deleted')),
    CONSTRAINT ck_customers_deleted_status
        CHECK (
            (status = 'deleted' AND deleted_time IS NOT NULL)
            OR (status IN ('active', 'archived') AND deleted_time IS NULL)
        )
);

CREATE INDEX idx_customers_status_name_active
    ON customers (status, lower(name), customer_id)
    WHERE deleted_time IS NULL;
