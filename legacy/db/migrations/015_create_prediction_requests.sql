ALTER TABLE prediction_versions
    ADD CONSTRAINT uq_prediction_versions_id_organisation
        UNIQUE (prediction_version_id, organisation_id);

CREATE TABLE prediction_requests (
    prediction_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    prediction_request_key TEXT NOT NULL,
    organisation_id BIGINT NOT NULL REFERENCES organisations(organisation_id),
    name TEXT NOT NULL,
    input_snapshot JSONB NOT NULL,
    state TEXT NOT NULL DEFAULT 'queued',
    submitted_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    start_time TIMESTAMPTZ,
    finish_time TIMESTAMPTZ,
    submitted_by BIGINT NOT NULL REFERENCES users(user_id),
    cancelled_by BIGINT REFERENCES users(user_id),
    cancellation_time TIMESTAMPTZ,
    worker_id TEXT,
    failure_code TEXT,
    failure_reason TEXT,
    completed_prediction_version_id BIGINT,
    CONSTRAINT uq_prediction_requests_key UNIQUE (prediction_request_key),
    CONSTRAINT uq_prediction_requests_completed_version
        UNIQUE (completed_prediction_version_id),
    CONSTRAINT fk_prediction_requests_completed_version_organisation
        FOREIGN KEY (completed_prediction_version_id, organisation_id)
        REFERENCES prediction_versions (prediction_version_id, organisation_id),
    CONSTRAINT ck_prediction_requests_key_non_blank
        CHECK (prediction_request_key ~ '[^[:space:]]'),
    CONSTRAINT ck_prediction_requests_name_non_blank
        CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_prediction_requests_snapshot_object
        CHECK (jsonb_typeof(input_snapshot) = 'object'),
    CONSTRAINT ck_prediction_requests_state
        CHECK (state IN (
            'queued', 'running', 'cancelling', 'completed', 'cancelled', 'failed'
        )),
    CONSTRAINT ck_prediction_requests_cancellation_audit
        CHECK ((cancellation_time IS NULL) = (cancelled_by IS NULL)),
    CONSTRAINT ck_prediction_requests_cancellation_state
        CHECK (
            (state IN ('cancelling', 'cancelled')) =
            (cancellation_time IS NOT NULL)
        ),
    CONSTRAINT ck_prediction_requests_start_state
        CHECK (
            (state = 'queued' AND start_time IS NULL)
            OR (
                state IN ('running', 'cancelling', 'completed', 'failed')
                AND start_time IS NOT NULL
            )
            OR state = 'cancelled'
        ),
    CONSTRAINT ck_prediction_requests_finish_state
        CHECK (
            (state IN ('completed', 'cancelled', 'failed')) =
            (finish_time IS NOT NULL)
        ),
    CONSTRAINT ck_prediction_requests_worker_state
        CHECK (
            (state IN ('running', 'cancelling')) = (worker_id IS NOT NULL)
            AND (worker_id IS NULL OR worker_id ~ '[^[:space:]]')
        ),
    CONSTRAINT ck_prediction_requests_completed_link
        CHECK (
            (state = 'completed') =
            (completed_prediction_version_id IS NOT NULL)
        ),
    CONSTRAINT ck_prediction_requests_failure_state
        CHECK (
            (state = 'failed') =
            (failure_code IS NOT NULL AND failure_reason IS NOT NULL)
            AND (failure_code IS NULL OR failure_code ~ '[^[:space:]]')
            AND (failure_reason IS NULL OR failure_reason ~ '[^[:space:]]')
        )
);

CREATE UNIQUE INDEX ux_prediction_requests_active_organisation_name
    ON prediction_requests (organisation_id, lower(name))
    WHERE state IN ('queued', 'running', 'cancelling');

CREATE INDEX idx_prediction_requests_queue
    ON prediction_requests (submitted_time, prediction_request_id)
    WHERE state = 'queued';

CREATE INDEX idx_prediction_requests_organisation_active
    ON prediction_requests (
        organisation_id,
        submitted_time,
        prediction_request_id
    )
    WHERE state IN ('queued', 'running', 'cancelling');

CREATE INDEX idx_prediction_requests_organisation_finished
    ON prediction_requests (
        organisation_id,
        finish_time DESC,
        prediction_request_id DESC
    );

COMMENT ON TABLE prediction_requests IS
    'Forecasting request history. Down migration destroys this history and requires stopped prediction workers.';
