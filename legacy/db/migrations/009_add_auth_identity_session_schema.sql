ALTER TABLE users
    ADD COLUMN email TEXT NOT NULL,
    ADD CONSTRAINT ck_users_email_non_blank
        CHECK (email ~ '[^[:space:]]');

CREATE UNIQUE INDEX ux_users_email_active
    ON users (lower(email))
    WHERE deleted_time IS NULL;

CREATE TABLE user_identities (
    user_identity_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_identities_issuer_non_blank
        CHECK (issuer ~ '[^[:space:]]'),
    CONSTRAINT ck_user_identities_subject_non_blank
        CHECK (subject ~ '[^[:space:]]'),
    CONSTRAINT ck_user_identities_login_time
        CHECK (last_login_time >= created_time),
    CONSTRAINT uq_user_identities_issuer_subject UNIQUE (issuer, subject),
    CONSTRAINT uq_user_identities_user_issuer UNIQUE (user_id, issuer)
);

CREATE TABLE oidc_login_transactions (
    state_hash BYTEA PRIMARY KEY,
    browser_binding_hash BYTEA NOT NULL,
    nonce TEXT NOT NULL,
    pkce_verifier TEXT NOT NULL,
    return_to TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_time TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_oidc_login_transactions_state_hash_length
        CHECK (octet_length(state_hash) = 32),
    CONSTRAINT ck_oidc_login_transactions_browser_hash_length
        CHECK (octet_length(browser_binding_hash) = 32),
    CONSTRAINT ck_oidc_login_transactions_nonce_non_blank
        CHECK (nonce ~ '[^[:space:]]'),
    CONSTRAINT ck_oidc_login_transactions_pkce_non_blank
        CHECK (pkce_verifier ~ '[^[:space:]]'),
    CONSTRAINT ck_oidc_login_transactions_return_to
        CHECK (return_to LIKE '/%' AND return_to NOT LIKE '//%'),
    CONSTRAINT ck_oidc_login_transactions_expiry
        CHECK (expires_time > created_time)
);

CREATE INDEX idx_oidc_login_transactions_expires_time
    ON oidc_login_transactions (expires_time);

CREATE INDEX idx_oidc_login_transactions_browser_binding_hash
    ON oidc_login_transactions (browser_binding_hash);

CREATE TABLE auth_sessions (
    session_id_hash BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_activity_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    absolute_expires_time TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_auth_sessions_id_hash_length
        CHECK (octet_length(session_id_hash) = 32),
    CONSTRAINT ck_auth_sessions_csrf_token_non_blank
        CHECK (csrf_token ~ '[^[:space:]]'),
    CONSTRAINT ck_auth_sessions_activity_time
        CHECK (last_activity_time >= created_time),
    CONSTRAINT ck_auth_sessions_absolute_expiry
        CHECK (absolute_expires_time > created_time)
);

CREATE INDEX idx_auth_sessions_user_id
    ON auth_sessions (user_id);

CREATE INDEX idx_auth_sessions_absolute_expires_time
    ON auth_sessions (absolute_expires_time);
