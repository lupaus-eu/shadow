-- ADR-015: AI change sets staged through MCP and applied only by a human.
-- Change-set history is never deleted. Deleting a grant during lazy cleanup
-- sets grant_id to null; created_by, client_id and client_name stay as the
-- audit record.

CREATE TABLE ai_change_sets (
    change_set_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    change_set_key TEXT NOT NULL,
    organisation_id BIGINT NOT NULL REFERENCES organisations(organisation_id),
    scenario_id BIGINT REFERENCES scenarios(scenario_id),
    title TEXT NOT NULL,
    rationale TEXT,
    status TEXT NOT NULL DEFAULT 'draft',
    grant_id BIGINT REFERENCES mcp_oauth_grants(grant_id) ON DELETE SET NULL,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    validation_result JSONB,
    applied_result JSONB,
    reviewed_by BIGINT REFERENCES users(user_id),
    reviewed_time TIMESTAMPTZ,
    review_note TEXT,
    created_by BIGINT NOT NULL REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ai_change_sets_key UNIQUE (change_set_key),
    CONSTRAINT ck_ai_change_sets_key_non_blank
        CHECK (change_set_key ~ '[^[:space:]]'),
    CONSTRAINT ck_ai_change_sets_title_non_blank
        CHECK (title ~ '[^[:space:]]'),
    CONSTRAINT ck_ai_change_sets_client_id_non_blank
        CHECK (client_id ~ '[^[:space:]]'),
    CONSTRAINT ck_ai_change_sets_client_name_length
        CHECK (length(client_name) BETWEEN 1 AND 100),
    CONSTRAINT ck_ai_change_sets_status
        CHECK (status IN (
            'draft', 'submitted', 'applied', 'rejected', 'failed', 'discarded'
        )),
    CONSTRAINT ck_ai_change_sets_validation_result_object
        CHECK (
            validation_result IS NULL
            OR jsonb_typeof(validation_result) = 'object'
        ),
    CONSTRAINT ck_ai_change_sets_applied_result
        CHECK (
            (status IN ('applied', 'failed')) = (applied_result IS NOT NULL)
            AND (
                applied_result IS NULL
                OR jsonb_typeof(applied_result) = 'object'
            )
        ),
    CONSTRAINT ck_ai_change_sets_review_audit
        CHECK ((reviewed_by IS NULL) = (reviewed_time IS NULL)),
    CONSTRAINT ck_ai_change_sets_review_state
        CHECK (
            (status IN ('applied', 'rejected', 'failed')) =
            (reviewed_time IS NOT NULL)
        ),
    CONSTRAINT ck_ai_change_sets_review_note
        CHECK (review_note IS NULL OR reviewed_time IS NOT NULL)
);

CREATE INDEX idx_ai_change_sets_organisation_created
    ON ai_change_sets (organisation_id, created_time DESC, change_set_id DESC);

CREATE INDEX idx_ai_change_sets_scenario_created
    ON ai_change_sets (scenario_id, created_time DESC, change_set_id DESC)
    WHERE scenario_id IS NOT NULL;

CREATE INDEX idx_ai_change_sets_grant_id
    ON ai_change_sets (grant_id)
    WHERE grant_id IS NOT NULL;

CREATE TABLE ai_change_set_operations (
    change_set_operation_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    change_set_id BIGINT NOT NULL
        REFERENCES ai_change_sets(change_set_id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    ref TEXT,
    op_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    frozen_values JSONB,
    error JSONB,
    CONSTRAINT uq_ai_change_set_operations_position UNIQUE (change_set_id, position),
    CONSTRAINT uq_ai_change_set_operations_ref UNIQUE (change_set_id, ref),
    CONSTRAINT ck_ai_change_set_operations_position
        CHECK (position >= 0),
    CONSTRAINT ck_ai_change_set_operations_op_type
        CHECK (op_type IN (
            'create_scenario', 'copy_scenario', 'create_org_state',
            'create_node', 'create_edge', 'patch_node',
            'create_timeserie', 'set_timeserie_values',
            'generate_timeserie_values', 'create_derived_metric', 'create_event'
        )),
    CONSTRAINT ck_ai_change_set_operations_ref
        CHECK (
            ref IS NULL
            OR (
                ref ~ '^\$[A-Za-z][A-Za-z0-9_]{0,63}$'
                AND op_type IN (
                    'create_scenario', 'copy_scenario', 'create_org_state',
                    'create_event', 'create_derived_metric'
                )
            )
        ),
    CONSTRAINT ck_ai_change_set_operations_payload_object
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_ai_change_set_operations_frozen_values
        CHECK (
            frozen_values IS NULL
            OR (
                op_type = 'generate_timeserie_values'
                AND jsonb_typeof(frozen_values) = 'object'
            )
        ),
    CONSTRAINT ck_ai_change_set_operations_error_object
        CHECK (error IS NULL OR jsonb_typeof(error) = 'object')
);

COMMENT ON TABLE ai_change_sets IS
    'AI change sets staged through MCP. Only a human applies or rejects them. Down migration destroys this history.';
