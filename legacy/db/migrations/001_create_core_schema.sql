    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ
);

CREATE TABLE graph_nodes (
    graph_node_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    graph_id BIGINT NOT NULL REFERENCES graphs(graph_id) ON DELETE CASCADE,
    node_key TEXT NOT NULL,
    node_type_id BIGINT NOT NULL REFERENCES node_types(node_type_id),
    create_date DATE,
    position_x DOUBLE PRECISION,
    position_y DOUBLE PRECISION,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    timeserie_id BIGINT REFERENCES timeseries(timeserie_id) ON DELETE SET NULL,
    timeserie_secondary_id BIGINT REFERENCES timeseries(timeserie_id) ON DELETE SET NULL,
    created_by BIGINT REFERENCES users(user_id),
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    modified_by BIGINT REFERENCES users(user_id),
    modified_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by BIGINT REFERENCES users(user_id),
    deleted_time TIMESTAMPTZ
);

CREATE TABLE graph_edges (
    graph_edge_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    graph_id BIGINT NOT NULL REFERENCES graphs(graph_id) ON DELETE CASCADE,
    edge_key TEXT NOT NULL,
